// Disarm amount is -magic, not -99; patch here so the table stays typed.
EFFECTS.Disarm = { ops: [{ op: "power", id: "Strength", target: "target", amount: "magic" }] };

function autoEffect(def: CardDef): EffectDef {
  const ops: Op[] = [];
  const d = `${def.description.eng} ${def.description.zhs}`.toLowerCase();
  if (def.type === "attack") {
    const tgt = def.target === "all_enemy" || def.multiDamage ? "all_enemies" : "target";
    ops.push({ op: "damage", target: tgt, amount: "damage" });
  }
  if (def.base.block) ops.push({ op: "block", amount: "block" });
  if (d.includes("poison") || d.includes("中毒"))
    ops.push({
      op: "power",
      id: "Poison",
      target: def.target === "all_enemy" ? "all_enemies" : "target",
      amount: "magic",
    });
  if (def.type === "power" && !ops.length) ops.push({ op: "power", id: def.id, target: "self", amount: "magic" });
  return { ops, verified: "auto" } as EffectDef;
}

export function effectOf(id: string): EffectDef {
  if (EFFECTS[id]) return EFFECTS[id]!;
  const def = CARD_BY_ID.get(id);
  return def ? autoEffect(def) : { ops: [] };
}
