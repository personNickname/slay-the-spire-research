import type { CardDef } from "./types.js";

export type Amt = number | "damage" | "block" | "magic" | "x" | "energy" | "handSize";

export type Op =
  | { op: "damage"; target?: "target" | "all_enemies" | "random_enemy"; amount?: Amt; times?: Amt; vampire?: boolean }
  | { op: "block"; amount?: Amt }
  | { op: "power"; id: string; target?: "target" | "self" | "all_enemies"; amount?: Amt }
  | { op: "draw"; amount?: Amt }
  | { op: "energy"; amount?: Amt }
  | { op: "loseHp"; amount?: Amt; target?: "self" }
  | { op: "heal"; amount?: Amt }
  | { op: "addCard"; card: string; to: "hand" | "discard" | "draw"; count?: number }
  | { op: "copySelf"; to: "discard" | "draw" }
  | { op: "doubleBlock" }
  | { op: "channel"; orb: "lightning" | "frost" | "dark" | "plasma"; count?: Amt }
  | { op: "evoke"; times?: Amt }
  | { op: "stance"; stance: "calm" | "wrath" | "divinity" | "none" }
  | { op: "custom"; id: string }
  | { op: "if"; cond: "targetVulnerable" | "targetAttacking" | "upgraded" | "targetPoisoned"; then: Op[]; else?: Op[] };

export interface EffectDef {
  ops: Op[];
  canUse?: "allAttacksInHand";
  onExhaust?: Op[];
  onEndOfTurnInHand?: Op[];
  onOtherCardPlayed?: Op[];
  onDraw?: Op[];
}

