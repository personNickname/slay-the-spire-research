const blk = (): Op => ({ op: "block", amount: "block" });
const pow = (id: string, target: Op extends { target?: infer T } ? T : never = "self" as never, amount: Amt = "magic"): Op => ({
  op: "power",
  id,
  target: target as "self",
  amount,
});

